#!/usr/bin/env node
/**
 * One-off generator: scans public/ for raster images and produces a tiny
 * base64 blur placeholder for each, written to lib/blurPlaceholders.ts.
 *
 * Next.js can auto-generate blur placeholders only for statically-imported
 * images; this site references images by string path (`/foo.jpg`), so we
 * generate them ourselves. Re-run this whenever images in public/ change:
 *
 *   node scripts/generate-blur-placeholders.mjs
 */
import { readdir, writeFile } from 'fs/promises';
import path from 'path';
import sharp from 'sharp';

const PUBLIC_DIR = path.join(process.cwd(), 'public');
const OUT_FILE = path.join(process.cwd(), 'lib', 'blurPlaceholders.ts');
const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png']);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(full)));
    } else if (IMAGE_EXT.has(path.extname(entry.name).toLowerCase())) {
      files.push(full);
    }
  }
  return files;
}

async function main() {
  const files = await walk(PUBLIC_DIR);
  const entries = [];

  for (const file of files) {
    const publicPath = '/' + path.relative(PUBLIC_DIR, file).split(path.sep).join('/');
    try {
      const buffer = await sharp(file)
        .resize(16, 16, { fit: 'inside' })
        .jpeg({ quality: 40 })
        .toBuffer();
      const dataUrl = `data:image/jpeg;base64,${buffer.toString('base64')}`;
      entries.push([publicPath, dataUrl]);
      console.log(`✓ ${publicPath}`);
    } catch (err) {
      console.warn(`skip ${publicPath}: ${err.message}`);
    }
  }

  entries.sort(([a], [b]) => a.localeCompare(b));

  const body = entries.map(([p, url]) => `  ${JSON.stringify(p)}: ${JSON.stringify(url)},`).join('\n');

  // Precomputed here (Node-side) so the generated file has no Node-only
  // APIs — it's imported by client components too.
  const fallbackSvg =
    '<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16"><rect width="16" height="16" fill="#191919"/></svg>';
  const fallbackDataUrl = `data:image/svg+xml;base64,${Buffer.from(fallbackSvg).toString('base64')}`;

  const output = `// AUTO-GENERATED by scripts/generate-blur-placeholders.mjs — do not edit by hand.
// Re-run the script after adding/changing images in public/.

const blurPlaceholders: Record<string, string> = {
${body}
};

// Generic dark-gradient fallback for any path not in the map above.
const FALLBACK_BLUR = ${JSON.stringify(fallbackDataUrl)};

export function getBlurDataURL(src: string): string {
  return blurPlaceholders[src] ?? FALLBACK_BLUR;
}
`;

  await writeFile(OUT_FILE, output);
  console.log(`\nWrote ${entries.length} placeholders to lib/blurPlaceholders.ts`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
